'use client'
import React, { useCallback, useEffect, useState } from 'react'
import Link from 'next/link'
import { Download, Trash2 } from 'lucide-react'
import AdminShell from '@/components/AdminShell'
import { Badge, Button, Card, ConfirmDialog, EmptyState, NoticeBar, Spinner, api, inputClass, type Notice } from '@/components/ui'
import { LedgerPager, td, tdRight, th, thRight } from '@/components/finance/LedgerLabels'
import { FORMAT_LABELS, downloadFile, formatBytes, istTime } from '@/components/reports/download'
import { DELIVERY_NOTE, EXPORT_FORMATS, REPORT_CATALOG } from '@/lib/resources/reports'

interface ReportFile {
  _id: string
  name: string
  reportType: string
  reportName: string
  period: string
  format: string
  size: number
  sha256: string
  rows: number
  totalRows: number
  generatedBy: string
  trigger: 'manual' | 'run_now' | 'schedule'
  scheduleName?: string | null
  createdAt: string
  expiresAt: string
  downloads: number
  lastDownloadedAt?: string | null
  lastDownloadedBy?: string | null
}

interface FilesResponse {
  items: ReportFile[]
  total: number
  page: number
  pageSize: number
  hiddenFromYou: number
  retentionDays: number
  retentionLimits: { min: number; max: number }
  maxFileBytes: number
  canManage: boolean
}

const TRIGGER_LABELS: Record<string, string> = {
  manual: 'Generated by hand',
  run_now: 'Schedule, "Run now"',
  schedule: 'Schedule, automatic',
}

function FilesBody() {
  const [data, setData] = useState<FilesResponse | null>(null)
  const [loading, setLoading] = useState(true)
  const [notice, setNotice] = useState<Notice>(null)
  const [page, setPage] = useState(1)
  const [type, setType] = useState('')
  const [format, setFormat] = useState('')
  const [busy, setBusy] = useState<string | null>(null)
  const [toDelete, setToDelete] = useState<ReportFile | null>(null)
  const [deleting, setDeleting] = useState(false)
  const [retention, setRetention] = useState('')
  const [savingRetention, setSavingRetention] = useState(false)
  const [confirmRetention, setConfirmRetention] = useState(false)

  const load = useCallback(async () => {
    setLoading(true)
    try {
      const params = new URLSearchParams({ page: String(page) })
      if (type) params.set('type', type)
      if (format) params.set('format', format)
      const result = await api<FilesResponse>('/api/admin/reports/files?' + params.toString())
      setData(result)
      setRetention(String(result.retentionDays))
    } catch (error: any) {
      setNotice({ type: 'error', text: error.message || 'Could not load the generated files.' })
    } finally {
      setLoading(false)
    }
  }, [page, type, format])

  useEffect(() => {
    load()
  }, [load])

  const download = async (file: ReportFile) => {
    setBusy(file._id)
    try {
      const result = await downloadFile(`/api/admin/reports/files/${file._id}/download`)
      setNotice({ type: 'success', text: `Downloaded ${result.filename} (${formatBytes(result.size)}). The download was recorded in the activity log.` })
      await load()
    } catch (error: any) {
      setNotice({ type: 'error', text: error.message || 'The download failed.' })
      await load()
    } finally {
      setBusy(null)
    }
  }

  const remove = async (reason: string) => {
    if (!toDelete) return
    setDeleting(true)
    try {
      await api(`/api/admin/reports/files/${toDelete._id}`, { method: 'DELETE', body: { reason } })
      setNotice({ type: 'success', text: `${toDelete.name} was deleted.` })
      setToDelete(null)
      await load()
    } catch (error: any) {
      setNotice({ type: 'error', text: error.message || 'Could not delete the file.' })
    } finally {
      setDeleting(false)
    }
  }

  const retentionNumber = Number(retention)
  const retentionValid =
    data !== null && Number.isInteger(retentionNumber) && retentionNumber >= data.retentionLimits.min && retentionNumber <= data.retentionLimits.max

  const saveRetention = async (reason: string) => {
    setSavingRetention(true)
    try {
      const result = await api<{ retentionDays: number; expiredFilesDeleted: number }>('/api/admin/reports/files', {
        method: 'PATCH',
        body: { retentionDays: retentionNumber, reason },
      })
      setNotice({
        type: 'success',
        text: `Files are now kept for ${result.retentionDays} days. ${
          result.expiredFilesDeleted > 0 ? `${result.expiredFilesDeleted} file(s) older than that were deleted.` : 'No stored file was older than that.'
        }`,
      })
      setConfirmRetention(false)
      await load()
    } catch (error: any) {
      setNotice({ type: 'error', text: error.message || 'Could not save the retention period.' })
    } finally {
      setSavingRetention(false)
    }
  }

  return (
    <>
      <NoticeBar notice={notice} onClose={() => setNotice(null)} />
      <NoticeBar
        notice={{
          type: 'info',
          text:
            'Generated files are stored inside the database, not at a public address. A file can only be downloaded here, by a signed-in admin who holds the permissions of the report it contains, and every download is recorded in the activity log with the file checksum. ' +
            DELIVERY_NOTE,
        }}
      />

      <Card className="p-4 mb-4">
        <div className="grid gap-4 md:grid-cols-4 items-end">
          <div>
            <label htmlFor="file-report" className="block text-sm font-medium text-gray-700 mb-1">
              Report
            </label>
            <select
              id="file-report"
              value={type}
              onChange={(e) => {
                setPage(1)
                setType(e.target.value)
              }}
              className={inputClass}
            >
              <option value="">All reports I have access to</option>
              {REPORT_CATALOG.map((report) => (
                <option key={report.key} value={report.key}>
                  {report.label}
                </option>
              ))}
            </select>
          </div>
          <div>
            <label htmlFor="file-format" className="block text-sm font-medium text-gray-700 mb-1">
              Format
            </label>
            <select
              id="file-format"
              value={format}
              onChange={(e) => {
                setPage(1)
                setFormat(e.target.value)
              }}
              className={inputClass}
            >
              <option value="">All formats</option>
              {EXPORT_FORMATS.map((item) => (
                <option key={item.value} value={item.value}>
                  {item.label}
                </option>
              ))}
            </select>
          </div>
          <div className="md:col-span-2">
            {data?.canManage ? (
              <form
                className="flex items-end gap-2"
                onSubmit={(event) => {
                  event.preventDefault()
                  if (retentionValid && retentionNumber !== data.retentionDays) setConfirmRetention(true)
                }}
              >
                <div className="flex-1">
                  <label htmlFor="retention-days" className="block text-sm font-medium text-gray-700 mb-1">
                    Keep files for (days)
                  </label>
                  <input
                    id="retention-days"
                    type="number"
                    min={data.retentionLimits.min}
                    max={data.retentionLimits.max}
                    step={1}
                    value={retention}
                    onChange={(e) => setRetention(e.target.value)}
                    className={inputClass}
                  />
                </div>
                <Button type="submit" variant="secondary" disabled={!retentionValid || retentionNumber === data.retentionDays}>
                  Save
                </Button>
              </form>
            ) : (
              data && (
                <p className="text-sm text-gray-600">
                  Files are kept for <span className="font-medium text-gray-800">{data.retentionDays} days</span> and then deleted.
                </p>
              )
            )}
          </div>
        </div>
        {data && (
          <p className="text-xs text-gray-500 mt-3">
            A file is deleted once it is older than {data.retentionDays} days. Largest file that can be stored: {formatBytes(data.maxFileBytes)}. Times are shown in
            Asia/Kolkata (IST).
            {data.hiddenFromYou > 0 && (
              <>
                {' '}
                {data.hiddenFromYou} more file{data.hiddenFromYou === 1 ? '' : 's'} exist{data.hiddenFromYou === 1 ? 's' : ''} for reports your role cannot open; they
                are not listed.
              </>
            )}
          </p>
        )}
      </Card>

      {loading && !data && <Spinner label="Loading the generated files..." />}

      {data && (
        <Card className={`overflow-hidden ${loading ? 'opacity-60' : ''}`}>
          {data.items.length === 0 ? (
            <EmptyState
              title="No generated files"
              hint={
                type || format
                  ? 'No stored file matches these filters.'
                  : 'Files appear here when a schedule runs (automatically or with "Run now" on Scheduled Reports) and when someone uses "Generate and save" on the Reports screen.'
              }
            />
          ) : (
            <div className="overflow-x-auto">
              <table className="min-w-full divide-y divide-gray-200">
                <thead className="bg-gray-50">
                  <tr>
                    <th className={th}>File</th>
                    <th className={th}>Period</th>
                    <th className={th}>Format</th>
                    <th className={thRight}>Size</th>
                    <th className={th}>Generated</th>
                    <th className={th}>Expires</th>
                    <th className={thRight}>Downloads</th>
                    <th className={th}>
                      <span className="sr-only">Actions</span>
                    </th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-gray-100">
                  {data.items.map((file) => (
                    <tr key={file._id} data-file={file._id}>
                      <td className={td}>
                        <p className="font-medium text-gray-800">{file.reportName}</p>
                        <p className="text-xs text-gray-500 break-all">{file.name}</p>
                        <p className="text-xs text-gray-400 break-all" title="SHA-256 checksum of the file">
                          SHA-256 {file.sha256}
                        </p>
                      </td>
                      <td className={td}>
                        {file.period}
                        <p className="text-xs text-gray-500">
                          {file.rows === file.totalRows ? `${file.rows} rows` : `${file.rows} of ${file.totalRows} rows`}
                        </p>
                      </td>
                      <td className={td}>
                        <Badge tone={file.format === 'pdf' ? 'red' : file.format === 'xlsx' ? 'green' : 'gray'}>{FORMAT_LABELS[file.format] || file.format}</Badge>
                      </td>
                      <td className={tdRight}>{formatBytes(file.size)}</td>
                      <td className={td}>
                        {istTime(file.createdAt)}
                        <p className="text-xs text-gray-500">
                          {file.generatedBy === 'schedule' ? 'by the scheduler' : `by ${file.generatedBy}`} · {TRIGGER_LABELS[file.trigger] || file.trigger}
                          {file.scheduleName ? ` (${file.scheduleName})` : ''}
                        </p>
                      </td>
                      <td className={td}>{istTime(file.expiresAt, false)}</td>
                      <td className={tdRight}>
                        {file.downloads || 0}
                        {file.lastDownloadedAt && (
                          <p className="text-xs text-gray-500 whitespace-normal">
                            last {istTime(file.lastDownloadedAt)}
                            {file.lastDownloadedBy ? ` by ${file.lastDownloadedBy}` : ''}
                          </p>
                        )}
                      </td>
                      <td className={td}>
                        <div className="flex items-center justify-end gap-2">
                          <Button variant="secondary" onClick={() => download(file)} loading={busy === file._id} disabled={busy !== null} data-action="download">
                            {busy !== file._id && <Download size={14} />}
                            Download
                          </Button>
                          {data.canManage && (
                            <Button variant="ghost" onClick={() => setToDelete(file)} disabled={busy !== null} aria-label={`Delete ${file.name}`} data-action="delete">
                              <Trash2 size={16} />
                            </Button>
                          )}
                        </div>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
          <LedgerPager page={data.page} pageSize={data.pageSize} total={data.total} onPage={setPage} />
        </Card>
      )}

      <p className="text-sm text-gray-600 mt-4">
        To create a file, open{' '}
        <Link href="/reports" className="text-teal font-medium hover:underline">
          Reports
        </Link>{' '}
        and choose &quot;Generate and save&quot;, or set up a schedule under{' '}
        <Link href="/reports/scheduled" className="text-teal font-medium hover:underline">
          Scheduled Reports
        </Link>
        .
      </p>

      <ConfirmDialog
        open={toDelete !== null}
        title="Delete this file?"
        message={
          toDelete ? (
            <>
              <span className="font-medium">{toDelete.name}</span> will be removed for everyone and cannot be restored. The report can be generated again from the
              Reports screen.
            </>
          ) : (
            ''
          )
        }
        confirmLabel="Delete file"
        danger
        askReason
        reasonRequired
        busy={deleting}
        onConfirm={remove}
        onClose={() => setToDelete(null)}
      />
      <ConfirmDialog
        open={confirmRetention}
        title="Change how long files are kept?"
        message={
          data ? (
            <>
              Files will be kept for <span className="font-medium">{retentionNumber} days</span> instead of {data.retentionDays}. This applies to the files already
              stored: any file older than {retentionNumber} days is deleted straight away.
            </>
          ) : (
            ''
          )
        }
        confirmLabel="Save retention"
        danger={data !== null && retentionNumber < data.retentionDays}
        askReason
        busy={savingRetention}
        onConfirm={saveRetention}
        onClose={() => setConfirmRetention(false)}
      />
    </>
  )
}

export default function ReportFilesPage() {
  return (
    <AdminShell title="Generated Files" subtitle="Stored report files: permission-checked, audited downloads that expire automatically">
      <FilesBody />
    </AdminShell>
  )
}
